'use strict';
// Lightweight execution of Node-RED Function source with mock context.
const fs=require('fs');
const path=require('path');
const assert=require('assert');
const nodes=JSON.parse(fs.readFileSync(path.join(__dirname,'../node-red/flows.json'),'utf8'));
const funcs=Object.fromEntries(nodes.filter(n=>n.type==='function').map(n=>[n.id,n]));
const memory={};
const flow={get:k=>memory[k],set:(k,v)=>{memory[k]=v;}};
const global={get:k=>k==='apiKey'?'test-secret':null};
const warnings=[];
const node={warn:x=>warnings.push(x),status:()=>{},error:x=>warnings.push(x),send:()=>{}};
function execute(id,msg){return new Function('msg','flow','global','node',funcs[id].func)(msg,flow,global,node);}
const sensor={payload:{suhu:29,kelembaban:67,timestamp:'2026-11-23T12:00:00Z'}};
let msg=execute('validate_sensor',sensor);
assert.equal(msg.params.$suhu,29);
assert.equal(msg.params.$humid,67);
assert.equal(execute('validate_sensor',{payload:{suhu:'not-a-number',kelembaban:60}}),null);
assert.equal(execute('validate_sensor',{payload:{suhu:23,kelembaban:101}}),null);
memory.threshold=30;
let out=execute('process_sensor',{sensor:{suhu:29,kelembaban:66,received:'1'}});
assert(out[0].wsEvent.type==='sensor' && out[1]===null);
out=execute('process_sensor',{sensor:{suhu:31,kelembaban:66,received:'2'}});
assert(out[1].alert && out[1].alert.threshold===30);
out=execute('process_sensor',{sensor:{suhu:33,kelembaban:66,received:'3'}});
assert(out[1]===null,'Notification must not spam while above threshold');
out=execute('process_sensor',{sensor:{suhu:27,kelembaban:66,received:'4'}});
assert(out[1]===null);
out=execute('process_sensor',{sensor:{suhu:32,kelembaban:66,received:'5'}});
assert(out[1].alert,'New crossing should notify');
out=execute('put_validate',{payload:{threshold:29.5}});
assert.equal(out[0].params.$value,29.5);
out=execute('put_validate',{payload:{threshold:-1}});
assert.equal(out[1].statusCode,400);
out=execute('check_control',{payload:{device:'lamp',action:'on'}});
assert.equal(JSON.parse(out[1].payload).action,'on');
out=execute('check_control',{payload:{device:'lamp',action:'invalid'}});
assert.equal(out[0].statusCode,400);
out=execute('ws_auth',{payload:JSON.stringify({type:'auth',api_key:'bad-key'}),_session:{id:'s1',type:'websocket'}});
assert.equal(JSON.parse(out.payload).type,'error');
assert.deepEqual(memory.wsSessions,undefined);
out=execute('ws_auth',{payload:JSON.stringify({type:'auth',api_key:'test-secret'}),_session:{id:'s1',type:'websocket'}});
assert.equal(JSON.parse(out.payload).type,'authenticated');
out=execute('ws_broadcast',{wsEvent:{type:'sensor',data:{suhu:31}}});
assert.equal(out[0].length,1);
assert.equal(out[0][0]._session.id,'s1');
assert.equal(JSON.parse(out[0][0].payload).type,'sensor');
console.log('SUKSES: validasi sensor, threshold crossing, API kontrol, key WebSocket & broadcast.');
